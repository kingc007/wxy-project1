// Copies the shared, manager-built rules tables into the app and generates a static index module so the
// engine runs identically in Node, Vitest and the browser bundle. Run via `npm run sync-rules`.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(here, "..");
const srcDir = path.resolve(appRoot, "../../shared/rules");
const dstDir = path.resolve(appRoot, "lib/zoning/rules");

if (!fs.existsSync(srcDir)) {
  console.error(`sync-rules: source directory not found: ${srcDir}`);
  process.exit(1);
}
fs.mkdirSync(dstDir, { recursive: true });

const files = fs.readdirSync(srcDir).filter((f) => f.endsWith(".json")).sort();
if (files.length === 0) {
  console.error(`sync-rules: no *.json files in ${srcDir}`);
  process.exit(1);
}
for (const f of files) {
  const text = fs.readFileSync(path.join(srcDir, f), "utf8");
  JSON.parse(text); // fail fast on invalid JSON
  fs.writeFileSync(path.join(dstDir, f), text);
}
// remove stale copies that no longer exist upstream
for (const f of fs.readdirSync(dstDir)) {
  if (f.endsWith(".json") && !files.includes(f)) fs.unlinkSync(path.join(dstDir, f));
}

const ident = (i) => `file${i}`;
const index = [
  "// GENERATED by scripts/sync-rules.mjs from ../../shared/rules/*.json. Do not edit.",
  'import type { RuleFile } from "../model";',
  ...files.map((f, i) => `import ${ident(i)} from "./${f}";`),
  "",
  `export const ruleFiles: RuleFile[] = [${files.map((_, i) => `${ident(i)} as unknown as RuleFile`).join(", ")}];`,
  "",
].join("\n");
fs.writeFileSync(path.join(dstDir, "index.ts"), index);
console.log(`sync-rules: copied ${files.length} file(s): ${files.join(", ")}`);
