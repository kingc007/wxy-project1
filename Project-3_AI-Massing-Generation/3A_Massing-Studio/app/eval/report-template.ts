// Self-contained HTML report for the eval: summary table plus inline SVG axon thumbnails per run.
import { axonSvg } from "../src/lib/export/svgAxon";
import type { Prism } from "@wxy/massing";

export interface EvalOption {
  slot: number;
  typology: string;
  source: string;
  status: string;
  overall: string;
  failCount: number;
  gfa: number;
  far: number;
  prisms: Prism[];
}
export interface EvalRun {
  envelope: string;
  /** true = SAMPLE envelope; false = real envelope from Project 1. */
  sample: boolean;
  notRealisable: number;
  empty: number;
  brief: string;
  mode: "offline" | "ai";
  options: EvalOption[];
  pctNoFails: number;
  pctPass: number;
  diversity: number;
  programFitPct: number | null;
  latencyMs: number;
  costUsd: number;
}

const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const pct = (v: number | null) => (v === null ? "n/a" : `${v.toFixed(0)}%`);

export function renderReport(runs: EvalRun[], meta: { generatedBy: string }): string {
  const rows = runs
    .map(
      (r) =>
        `<tr><td>${esc(r.envelope)} ${r.sample ? "(SAMPLE)" : "(real, Project 1)"}</td><td>${esc(r.brief)}</td><td>${r.mode}</td><td>${pct(r.pctNoFails)}</td><td>${pct(r.pctPass)}</td><td>${r.diversity.toFixed(3)}</td><td>${pct(r.programFitPct)}</td><td>${r.latencyMs.toFixed(0)}</td><td>$${r.costUsd.toFixed(4)}</td><td>${r.notRealisable}</td><td>${r.empty}</td></tr>`,
    )
    .join("\n");
  const cards = runs
    .map((r, ri) => {
      const thumbs = r.options
        .map((o, oi) => {
          const svg = axonSvg(o.prisms, { size: [180, 140], style: "model", theme: "light", idPrefix: `r${ri}o${oi}` });
          return `<figure>${svg}<figcaption>${o.slot + 1}. ${esc(o.typology)}<br>${esc(o.overall)} · GFA ${Math.round(o.gfa / 10) * 10} sf · FAR ${o.far.toFixed(2)}<br><small>${esc(o.source === "builtin" ? "Built-in (no AI)" : "AI")}</small></figcaption></figure>`;
        })
        .join("");
      return `<section><h3>${esc(r.envelope)} ${r.sample ? "(SAMPLE)" : "(real)"} × ${esc(r.brief)} <small>(${r.mode})</small></h3><div class="row">${thumbs}</div></section>`;
    })
    .join("\n");
  return `<!doctype html><html lang="en"><meta charset="utf-8"><title>3A Massing Studio — eval</title>
<style>body{font:14px system-ui,sans-serif;margin:24px;color:#222}table{border-collapse:collapse}td,th{border:1px solid #ccc;padding:4px 8px;text-align:right}td:first-child,td:nth-child(2),td:nth-child(3),th{text-align:left}.row{display:flex;flex-wrap:wrap;gap:8px}figure{margin:0;width:190px;font-size:12px}small{color:#666}</style>
<h1>3A Massing Studio — eval</h1>
<p>SAMPLE envelopes; SIMPLIFIED engine rules. "No fails" = zero failing rules (Review rows allowed). "Pass" = Passes all rules. Program fit = share of program targets within ±5%. Generated by ${esc(meta.generatedBy)}.</p>
<table><thead><tr><th>Envelope</th><th>Brief</th><th>Mode</th><th>No fails</th><th>Pass</th><th>Diversity</th><th>Program fit</th><th>Latency ms</th><th>Cost</th><th>Not realisable</th><th>Empty</th></tr></thead><tbody>
${rows}
</tbody></table>
<h2>Options</h2>
${cards}
</html>
`;
}
